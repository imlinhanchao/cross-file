import { base32Encode, base64urlEncode, base64urlDecode, randomBytes } from "./bytes.js";

/** docs/02 §1: roomId = 16 random bytes, base32 encoded (26 chars), public. */
export const ROOM_ID_BYTES = 16;
/** docs/02 §1: roomKey = 32 random bytes, only ever in the URL fragment or an SAS-authenticated channel. */
export const ROOM_KEY_BYTES = 32;
/** join proof nonce; size is not fixed by the protocol doc, 16 bytes is what we generate. */
export const GUEST_NONCE_BYTES = 16;
/** docs/02 §4.1: per-file 4 byte salt. */
export const FILE_SALT_BYTES = 4;

export interface RoomIdentity {
  /** base32 text, safe in URLs and logs *by the host only* (roomId is public). */
  roomId: string;
  /** raw 16 bytes used as HKDF salt. */
  roomIdBytes: Uint8Array;
  /** raw 32 byte secret. Never send to the signaling server. */
  roomKey: Uint8Array;
}

export function createRoomIdentity(): RoomIdentity {
  const roomIdBytes = randomBytes(ROOM_ID_BYTES);
  return {
    roomId: base32Encode(roomIdBytes),
    roomIdBytes,
    roomKey: randomBytes(ROOM_KEY_BYTES),
  };
}

export function createGuestNonce(): string {
  return base64urlEncode(randomBytes(GUEST_NONCE_BYTES));
}

export function createFileSalt(): Uint8Array {
  return randomBytes(FILE_SALT_BYTES);
}

/** `https://host/r/<roomId>#<roomKey>` — the key lives in the fragment only (docs/01 D3). */
export function buildRoomLink(origin: string, roomId: string, roomKey: Uint8Array): string {
  const base = origin.replace(/\/+$/, "");
  return `${base}/r/${roomId}#${base64urlEncode(roomKey)}`;
}

export function parseRoomLink(url: string): { roomId: string; roomKey: Uint8Array } | null {
  try {
    const parsed = new URL(url);
    const match = /\/r\/([a-z2-7]+)\/?$/.exec(parsed.pathname);
    if (!match) return null;
    const roomId = match[1]!;
    const fragment = parsed.hash.replace(/^#/, "");
    if (!fragment) return null;
    const roomKey = base64urlDecode(fragment);
    if (roomKey.length !== ROOM_KEY_BYTES) return null;
    return { roomId, roomKey };
  } catch {
    return null;
  }
}

/** Six digit join code (docs/02 §3.5). Generated by the signaling server, 10 min, single use. */
export function normalizeJoinCode(input: string): string | null {
  const digits = input.replace(/[^0-9]/g, "");
  return digits.length === 6 ? digits : null;
}
